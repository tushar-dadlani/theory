(* The AIMO3 domain: all 13 canonical types are known examples *)
Definition aimo3_domain (e : Example) : Prop :=
  e = type_a  \/ e = type_b  \/ e = type_g  \/ e = type_d  \/ e = type_e  \/
  e = type_ab \/ e = type_ag \/ e = type_bd \/ e = type_ge  \/
  e = type_abd \/ e = type_bge \/ e = type_abg \/ e = type_abde.

(* The current kernel: exactly type_ge is not yet I_phase *)
Definition aimo3_kernel (e : Example) : Prop := e = type_ge.

Lemma aimo3_kern_in : forall e, aimo3_kernel e -> aimo3_domain e.
Proof.
  intros e Hk. unfold aimo3_kernel in Hk. subst.
  unfold aimo3_domain. right. right. right. right. right. right. right. right. left.
  reflexivity.
Qed.

Definition AIMO3 : InfoSystem := mkIS
  aimo3_domain
  aimo3_kernel
  aimo3_kern_in.

(* ================================================================= *)
(*  PART 5 — THE CLOSING THEOREMS                                     *)
(* ================================================================= *)

(* The remaining gap (type_ge) is reachable from atoms *)
Theorem aimo3_gap_is_reachable :
  AIMO3.(kernel) type_ge ->
  exists s, AIMO3.(domain) (atom s).
Proof.
  intros _. exists sym_gamma.
  (* atom sym_gamma = [sym_gamma] = type_g, which is in domain *)
  unfold aimo3_domain, atom. right. right. left. reflexivity.
Qed.

Lemma atom_gamma_is_type_g : atom sym_gamma = type_g.
Proof. reflexivity. Qed.

Lemma type_g_in_domain : AIMO3.(domain) type_g.
Proof. unfold aimo3_domain. right. right. left. reflexivity. Qed.

(* One D-step closes the type_ge gap *)
Theorem one_step_closes_aimo3 :
  AIMO3.(kernel) type_ge ->
  (IS_tower AIMO3 1).(domain) type_ge.
Proof.
  intros Hk.
  apply (three_things_suffice AIMO3).
  - (* show every kernel element has an atom in domain *)
    intros e He.
    (* He : kernel AIMO3 e = (e = type_ge) *)
    (* Reconstruct a kernel proof for type_ge after normalization *)
    assert (Heq : e = type_ge) by exact He.
    subst e.
    apply aimo3_gap_is_reachable.
    unfold aimo3_kernel. reflexivity.
  - exact Hk.
Qed.

(* After one step, type_ge enters the domain *)
Theorem type_ge_enters_domain :
  (IS_tower AIMO3 1).(domain) type_ge.
Proof.
  apply one_step_closes_aimo3.
  unfold aimo3_kernel. reflexivity.
Qed.

(* At the limit, AIMO3 is closed — kernel = ∅ *)
Theorem aimo3_limit_is_closed :
  forall e : Example,
  ~ (IS_limit AIMO3).(kernel) e.
Proof.
  exact (IS_limit_closed AIMO3).
Qed.

