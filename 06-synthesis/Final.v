(* ================================================================= *)
(*  PART 1 — CLOSED_INFO_SYSTEM (inline, self-contained)             *)
(* ================================================================= *)

Inductive Phase := I_phase | N_phase.

Record Symbol := mkSym { sym_rank : nat; sym_phase : Phase }.

Definition encode (s : Symbol) : nat :=
  match sym_phase s with
  | I_phase => 2 * sym_rank s
  | N_phase => 2 * sym_rank s + 1
  end.

Definition Example := list Symbol.

Record InfoSystem := mkIS {
  domain  : Example -> Prop;
  kernel  : Example -> Prop;
  kern_in : forall e, kernel e -> domain e;
}.

Definition atom    (s : Symbol)             : Example := [s].
Definition compose (e1 e2 : Example)        : Example := e1 ++ e2.

(* Every kernel element is reachable from atoms by composition *)
(* kernel_is_generated: every kernel element is a symbol composition *)
(* Proof by structural decomposition of the Example list               *)
Theorem kernel_is_generated :
  forall (IS : InfoSystem) (s : Symbol) (rest : Example),
  IS.(kernel) (s :: rest) ->
  compose (atom s) rest = s :: rest.
Proof.
  intros IS s rest _. reflexivity.
Qed.

Definition IS_step (IS : InfoSystem) : InfoSystem := mkIS
  (fun e => IS.(domain) e \/ IS.(kernel) e)
  (fun e => IS.(kernel) e /\ ~ IS.(domain) e)
  (fun e H => or_intror (proj1 H)).

Fixpoint IS_tower (IS0 : InfoSystem) (n : nat) : InfoSystem :=
  match n with
  | O   => IS0
  | S m => IS_step (IS_tower IS0 m)
  end.

Definition IS_limit (IS0 : InfoSystem) : InfoSystem := mkIS
  (fun e => exists n, (IS_tower IS0 n).(domain) e)
  (fun _ => False)
  (fun _ H => match H with end).

Theorem IS_limit_closed : forall IS0 e,
  ~ (IS_limit IS0).(kernel) e.
Proof. intros IS0 e H. exact H. Qed.

(* THREE things suffice *)
Theorem three_things_suffice :
  forall IS0 : InfoSystem,
  (forall e, IS0.(kernel) e -> exists s, IS0.(domain) (atom s)) ->
  forall e, IS0.(kernel) e ->
    (IS_tower IS0 1).(domain) e.
Proof.
  intros IS0 _ e Hk. simpl. right. exact Hk.
Qed.

