(* Each type is an Example = list Symbol *)
Definition type_a    : Example := [sym_alpha].
Definition type_b    : Example := [sym_beta].
Definition type_g    : Example := [sym_gamma].
Definition type_d    : Example := [sym_delta].
Definition type_e    : Example := [sym_epsilon].
Definition type_ab   : Example := [sym_alpha; sym_beta].
Definition type_ag   : Example := [sym_alpha; sym_gamma].
Definition type_bd   : Example := [sym_beta;  sym_delta].
Definition type_ge   : Example := [sym_gamma; sym_epsilon].
Definition type_abd  : Example := [sym_alpha; sym_beta;  sym_delta].
Definition type_bge  : Example := [sym_beta;  sym_gamma; sym_epsilon].
Definition type_abg  : Example := [sym_alpha; sym_beta;  sym_gamma].
Definition type_abde : Example := [sym_alpha; sym_beta;  sym_delta; sym_epsilon].

(* Every canonical type is a composition of atoms *)
Theorem types_are_compositions :
  compose (atom sym_alpha) (atom sym_beta) = type_ab /\
  compose (atom sym_alpha) (atom sym_gamma) = type_ag /\
  compose (atom sym_beta)  (atom sym_delta) = type_bd /\
  compose (atom sym_gamma) (atom sym_epsilon) = type_ge.
Proof. repeat split; reflexivity. Qed.

(* ================================================================= *)
(*  PART 4 — THE AIMO3 INFO SYSTEM                                   *)
(*                                                                    *)
(*  domain = the 13 canonical types (each is an Example)             *)
(*  kernel = the types not yet at I_phase (< 95% accuracy)           *)
(*                                                                    *)
