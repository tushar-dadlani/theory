  + 6*(x*(2*x-1)/3)*((1024*x^10-23040*x^9+222720*x^8-1209600*x^7+4049472*x^6-8618400*x^5+11578880*x^4-9381600*x^3+4106304*x^2-725760*x)/39916800)
  - 2*((16*x^4-48*x^3+44*x^2-12*x)/120)^3
