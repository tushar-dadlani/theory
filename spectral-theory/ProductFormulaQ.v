(* inject_Z of a nonzero integer is a nonzero rational *)
Lemma injZ_nonzero : forall z, (z <> 0)%Z -> ~ inject_Z z == 0.
Proof. intros z Hz Heq; apply Hz; unfold Qeq in Heq; simpl in Heq; lia. Qed.

(* a power of a nonzero rational is nonzero *)
Lemma qpow_nonzero : forall x k, ~ x == 0 -> ~ qpow x k == 0.
Proof.
  intros x k Hx; induction k as [|k IH]; cbn [qpow].
  - intro H; unfold Qeq in H; simpl in H; discriminate.
  - intro H; destruct (Qmult_integral _ _ H); [ apply Hx | apply IH ]; assumption.
Qed.

(* inject_Z commutes with taking a (natural) power: Z-power <-> qpow *)
Lemma inject_Z_pow : forall p k, inject_Z (p ^ Z.of_nat k) == qpow (inject_Z p) k.
Proof.
  intros p k; induction k as [|k IH].
  - replace (Z.of_nat 0) with 0%Z by reflexivity.
    rewrite Z.pow_0_r; reflexivity.
  - rewrite Nat2Z.inj_succ, Z.pow_succ_r by lia.
    rewrite inject_Z_mult, IH; cbn [qpow]; reflexivity.
Qed.

(* ----------------------------------------------------------------- *)
(*  THE FINITE-ADELIC ABSOLUTE-VALUE PRODUCT                         *)
(*                                                                    *)
(*  For n = code ps ks = prod_i (ps_i)^(ks_i), the product of the      *)
(*  non-archimedean absolute values is                                *)
(*     prod_p |n|_p  =  prod_i (ps_i)^(-ks_i)  =  fabs ps ks.          *)
(* ----------------------------------------------------------------- *)

Fixpoint fabs (ps : list Z) (ks : list nat) : Q :=
  match ps, ks with
  | p :: ps', k :: ks' => / qpow (inject_Z p) k * fabs ps' ks'
  | _, _ => 1
  end.

(* ----------------------------------------------------------------- *)
(*  THE PRODUCT FORMULA FOR A POSITIVE INTEGER                       *)
(*     |n|_infinity * prod_p |n|_p  =  n * prod_p p^{-v_p(n)}  =  1     *)
(* ----------------------------------------------------------------- *)

Lemma pf_int : forall ps ks, Forall prime ps -> length ps = length ks ->
  inject_Z (code ps ks) * fabs ps ks == 1.
Proof.
  induction ps as [|p ps' IH]; intros ks Hpr Hlen.
  - cbn [code fabs]; replace (inject_Z 1) with 1 by reflexivity; ring.
  - destruct ks as [|k ks']; [ simpl in Hlen; lia | ].
    inversion Hpr as [| ? ? Hp Hpr']; subst.
    cbn [code fabs].
    rewrite inject_Z_mult, inject_Z_pow.
    assert (Hq : ~ qpow (inject_Z p) k == 0)
      by (apply qpow_nonzero, injZ_nonzero; destruct Hp as [Hp1 _]; lia).
    setoid_replace
      (qpow (inject_Z p) k * inject_Z (code ps' ks')
         * (/ qpow (inject_Z p) k * fabs ps' ks'))
      with
      ((qpow (inject_Z p) k * / qpow (inject_Z p) k)
         * (inject_Z (code ps' ks') * fabs ps' ks'))
      by ring.
    rewrite (Qmult_inv_r _ Hq), Qmult_1_l.
    apply IH; [ exact Hpr' | simpl in Hlen; lia ].
Qed.

