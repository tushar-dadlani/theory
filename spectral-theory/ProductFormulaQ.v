(* the primes <= B, as a Z-list (local copy, keeps this file Reals-free) *)
Definition primes_upto (B : nat) : list Z :=
  filter (fun z => if prime_dec z then true else false)
         (map Z.of_nat (seq 0 (S B))).

Lemma primes_upto_Forall : forall B, Forall prime (primes_upto B).
Proof.
  intro B; apply Forall_forall; intros q Hq; unfold primes_upto in Hq.
  apply filter_In in Hq; destruct Hq as [_ Hf].
  destruct (prime_dec q) as [Hp | _]; [ exact Hp | discriminate ].
Qed.

Lemma NoDup_map_inj : forall (A B : Type) (f : A -> B) (l : list A),
  (forall x y, In x l -> In y l -> f x = f y -> x = y) -> NoDup l -> NoDup (map f l).
Proof.
  intros A B f l; induction l as [|a l IH]; intros Hinj Hnd; simpl; [ constructor | ].
  rewrite NoDup_cons_iff in Hnd; destruct Hnd as [Hna Hnd].
  rewrite NoDup_cons_iff; split.
  - intro Hin; apply in_map_iff in Hin; destruct Hin as [y [Hfy Hy]].
    assert (a = y) by (apply Hinj; [ left; reflexivity | right; exact Hy | symmetry; exact Hfy ]).
    subst y; contradiction.
  - apply IH; [ intros x y Hx Hy; apply Hinj; right; assumption | exact Hnd ].
Qed.

Lemma primes_upto_nodup : forall B, NoDup (primes_upto B).
Proof.
  intro B; unfold primes_upto; apply NoDup_filter.
  apply NoDup_map_inj; [ intros x y _ _ H; apply Nat2Z.inj; exact H | apply seq_NoDup ].
Qed.

Lemma primes_upto_complete : forall B q,
  prime q -> (q <= Z.of_nat B)%Z -> In q (primes_upto B).
Proof.
  intros B q Hp Hq; unfold primes_upto; apply filter_In.
  assert (Hq2 : (2 <= q)%Z) by (destruct Hp; lia).
  split.
  - apply in_map_iff; exists (Z.to_nat q); split.
    + apply Z2Nat.id; lia.
    + apply in_seq; split; [ lia | ].
      assert (Z.to_nat q <= B)%nat
        by (apply (proj2 (Nat2Z.inj_le (Z.to_nat q) B));
              rewrite Z2Nat.id by lia; exact Hq); lia.
  - destruct (prime_dec q) as [_ | Hnp]; [ reflexivity | contradiction ].
Qed.

Corollary product_formula_int : forall n, (0 < n)%Z ->
  exists ps ks,
       Forall prime ps
    /\ length ps = length ks
    /\ code ps ks = n                              (* n = prod_p p^{v_p(n)} *)
    /\ inject_Z n * fabs ps ks == 1.               (* |n|_inf * prod_p |n|_p = 1 *)
Proof.
  intros n Hn.
  set (B := Z.to_nat n).
  assert (Hsm : forall q, prime q -> (q | n)%Z -> In q (primes_upto B)).
  { intros q Hq Hqn.
    apply primes_upto_complete; [ exact Hq | ].
    unfold B; rewrite Z2Nat.id by lia.
    apply Z.divide_pos_le; [ exact Hn | exact Hqn ]. }
  destruct (code_surj (primes_upto B) (primes_upto_Forall B) (primes_upto_nodup B)
              n Hn Hsm) as [ks [Hlen Hcode]].
  exists (primes_upto B), ks.
  repeat split; [ apply primes_upto_Forall | exact Hlen | exact Hcode | ].
  rewrite <- Hcode; apply pf_int; [ apply primes_upto_Forall | exact Hlen ].
Qed.

(* ----------------------------------------------------------------- *)
(*  THE PRODUCT FORMULA FOR A POSITIVE RATIONAL                      *)
(*                                                                    *)
(*  Write x = a / b with a = code ps ea, b = code ps eb over a common   *)
(*  prime list ps (existence for both a and b from code_surj over      *)
(*  primes_upto of a*b).  Then                                        *)
(*     |x|_infinity          = inject_Z a / inject_Z b                 *)
(*     prod_p |x|_p          = (prod_p |a|_p) / (prod_p |b|_p)          *)
(*                          = fabs ps ea / fabs ps eb                  *)
(*  and their product is 1 -- the quotient of the two integer          *)
(*  instances (pf_int for a and for b).                               *)
(* ----------------------------------------------------------------- *)

Theorem product_formula_Q : forall ps ea eb,
  Forall prime ps -> length ps = length ea -> length ps = length eb ->
  (inject_Z (code ps ea) / inject_Z (code ps eb))     (* |x|_infinity, x = a/b *)
    * (fabs ps ea / fabs ps eb)                        (* prod_p |x|_p          *)
    == 1.
Proof.
  intros ps ea eb Hpr Hla Hlb.
  pose proof (pf_int ps ea Hpr Hla) as Pa.
  pose proof (pf_int ps eb Hpr Hlb) as Pb.
  set (Za := inject_Z (code ps ea)) in *.
  set (Zb := inject_Z (code ps eb)) in *.
  set (Fa := fabs ps ea) in *.
  set (Fb := fabs ps eb) in *.
  assert (Hrw : (Za / Zb) * (Fa / Fb) == (Za * Fa) * / (Zb * Fb)).
  { unfold Qdiv; rewrite Qinv_mult_distr; ring. }
  rewrite Hrw, Pa, Pb; now rewrite Qmult_1_l.
Qed.

Print Assumptions product_formula_int.
Print Assumptions product_formula_Q.

(* ================================================================= *)
(*  MASTER THEOREM                                                   *)
(* ================================================================= *)

Theorem product_formula :
  (* INTEGER: every positive integer factors, and its archimedean size  *)
  (* is the reciprocal of the product of its p-adic absolute values     *)
  (forall n, (0 < n)%Z -> exists ps ks,
      Forall prime ps /\ length ps = length ks
      /\ code ps ks = n /\ inject_Z n * fabs ps ks == 1)
  (* RATIONAL: for x = a/b over a common prime list, prod_v |x|_v = 1    *)
  /\ (forall ps ea eb, Forall prime ps ->
        length ps = length ea -> length ps = length eb ->
        (inject_Z (code ps ea) / inject_Z (code ps eb))
          * (fabs ps ea / fabs ps eb) == 1).
Proof.
  split; [ exact product_formula_int | exact product_formula_Q ].
Qed.

Print Assumptions product_formula.

