(* ── The four memory operations ──────────────────────────────────── *)
(*                                                                     *)
(* The API of human memory:                                           *)
(*   Read    — query -> projection onto nearest fixed point centroid  *)
(*   Write   — event -> running average centroid update               *)
(*   Label   — centroid -> auto-generated name (top words)            *)
(*   Summary — centroid -> auto-generated description                 *)
(*                                                                     *)
(* In the Rust code:                                                  *)
(*   read    ~ cosine similarity search over candidates               *)
(*   write   ~ MemoryEngine::process(event) -> StepResult            *)
(*   label   ~ MemoryEngine::auto_label(&centroid)                   *)
(*   summary ~ MemoryEngine::build_summary(candidate_idx)            *)
